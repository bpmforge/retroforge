/* RetroForge -- RF-Scroller (ticket W2-10) -- level data.
 *
 * Shape documented in ../FORMAT.md, designed to be decodable by the
 * `metatile_screens` decoder family (docs/design/GAME_PROFILES.md
 * [decode] section) -- that decoder is ticket W5-02a and does not exist
 * yet; this file is the data + a from-scratch runtime reader main.c
 * writes for itself, not an implementation of that decoder.
 *
 * All tables are plain `const` C arrays (default RODATA, linked into
 * ROM0) rather than a `.s` file: unlike the CHR pattern data (chr.s),
 * nothing here needs to land at a hardware-fixed address, and main.c
 * reads every one of these arrays directly, so plain C avoids an
 * asm/C linkage boundary for no benefit.
 */

#include "leveldata.h"

/* Metatile table (FORMAT.md "Metatile table"): 4 metatiles, 4 tile IDs
 * each (TL,TR,BL,BR), referencing chr.s's background pattern table. */
const unsigned char metatile_table[METATILE_COUNT][4] = {
    /* 0: sky            */ {0x00, 0x00, 0x00, 0x00},
    /* 1: ground          */ {0x01, 0x01, 0x02, 0x02},
    /* 2: landmark A      */ {0x03, 0x04, 0x05, 0x06},
    /* 3: landmark B      */ {0x07, 0x08, 0x09, 0x0A},
};

/* Collision table (FORMAT.md "Collision table"): one byte per metatile,
 * bit0=solid, bit1=platform, bit2=hazard. Documented for W2-10a /
 * W5-02a; THIS ticket's own game logic does not consult it at runtime
 * (see FORMAT.md's "What this ticket's runtime does NOT do" section) --
 * player-vs-world blocking here is a single hardcoded world-X bound
 * (MAX_PLAYER_X in main.c), not a per-metatile lookup. */
const unsigned char collision_table[METATILE_COUNT] = {
    /* 0: sky       */ 0x00,
    /* 1: ground     */ 0x01, /* solid */
    /* 2: landmark A */ 0x01, /* solid */
    /* 3: landmark B */ 0x01, /* solid */
};

/* Palette table (FORMAT.md "Palette table"): one area (this level has
 * exactly one), 4 background-palette bytes: [backdrop, index1, index2,
 * index3]. A degenerate (area-count=1) case of GAME_PROFILES.md's
 * `palettes = { ..., per_area = true }` shape, not a deviation from it. */
const unsigned char area_palette[4] = {0x0F, 0x00, 0x10, 0x30};

/* Sprite palette (player + sprite-0 sentinel): outside the "level
 * format" proper -- GAME_PROFILES.md's [decode].palettes section
 * documents only the background/area palette table above; sprites use a
 * separate, fixed palette this fixture just hardcodes. */
const unsigned char sprite_palette[4] = {0x0F, 0x16, 0x21, 0x30};

