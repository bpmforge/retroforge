//! Rust source emitter for lowered 6502 code (ticket W36-12): a developer
//! tool for reading a function and for writing replacement functions against
//! its shape. Not a runtime tier: nothing here compiles on a player's
//! machine, and **output for a commercial game is never committed** (it goes
//! under `target/` or stays on the developer's disk; law 5, D-021).
//!
//! One Rust function per atlas function, one `match` arm per instruction,
//! every bus cycle a `bus.read` / `bus.write` call in hardware order with a
//! comment naming what the cycle is for (the [`Cycle`] kinds), flag updates
//! spelled out. Dummy reads and read-modify-write write-backs are kept: a
//! replacement function written against this shape sees the same bus.
//!
//! Operand bytes are baked from the image (`rf_rebuild::ir::bake`), so
//! addresses read as constants. The emitted code does **not** model
//! interrupt polling: the [`MachineOp`]s appear as comments, and a function
//! returns to its caller when `pc` leaves the instructions it contains, or
//! at an instruction the lowering leaves to the interpreter.
//!
//! The output is self-contained (its own `Bus` trait and `Regs`), so
//! `rustc --crate-type lib --edition 2021` compiles it with no crate graph.

use std::collections::HashSet;
use std::fmt::Write as _;

use rf_rebuild::ir::{
    AluOp, Cycle, Dst, InterpretReason, LoweredFunction, Lowering, MachineOp, Op, Val, Width,
};
use rf_rebuild::{Atlas, Function};

use super::lower::{lower_function, A, P, PC, S, X, Y};
use crate::trace::{format_trace_line, TracePeek};

/// The header every emitted module starts with: lint allowances, the `Bus`
/// trait and the register file.
pub const PRELUDE: &str = "\
// Generated by rf-nes `rebuild::emit` (ticket W36-12). Developer tool output:
// do not commit for a commercial game.
#![allow(unused_assignments, unused_mut, unused_variables, unused_parens, dead_code)]
#![allow(clippy::all)]

/// One call per bus cycle. The implementor ticks its devices inside.
pub trait Bus {
    fn read(&mut self, addr: u16) -> u8;
    fn write(&mut self, addr: u16, val: u8);
}

/// The 6502 register file. `p` keeps bit 5 set and bit 4 clear.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct Regs {
    pub a: u8,
    pub x: u8,
    pub y: u8,
    pub s: u8,
    pub pc: u16,
    pub p: u8,
}
";

fn val(v: Val) -> String {
    match v {
        Val::Imm(x) => format!("{x:#06x}u16"),
        Val::Reg(r) if r == A => "u16::from(r.a)".into(),
        Val::Reg(r) if r == X => "u16::from(r.x)".into(),
        Val::Reg(r) if r == Y => "u16::from(r.y)".into(),
        Val::Reg(r) if r == S => "u16::from(r.s)".into(),
        Val::Reg(r) if r == PC => "r.pc".into(),
        Val::Reg(r) if r == P => "u16::from(r.p)".into(),
        Val::Reg(r) => format!("/* reg {} */ 0u16", r.0),
        Val::Tmp(t) => format!("t{}", t.0),
        Val::Flag(f) => format!("u16::from(r.p & {:#04x} != 0)", f.0),
    }
}

fn alu_expr(op: AluOp, w: Width, a: Val, b: Val) -> String {
    let (a, b) = (val(a), val(b));
    let body = match op {
        AluOp::Add => format!("{a}.wrapping_add({b})"),
        AluOp::Sub => format!("{a}.wrapping_sub({b})"),
        AluOp::And => format!("{a} & {b}"),
        AluOp::Or => format!("{a} | {b}"),
        AluOp::Xor => format!("{a} ^ {b}"),
        AluOp::Not => format!("!{a}"),
        AluOp::Shl => format!("{a}.wrapping_shl(u32::from({b}))"),
        AluOp::Shr => format!("{a}.wrapping_shr(u32::from({b}))"),
        AluOp::Eq => format!("u16::from({a} == {b})"),
        AluOp::Ne => format!("u16::from({a} != {b})"),
        AluOp::Ge => format!("u16::from({a} >= {b})"),
        AluOp::Gt => format!("u16::from({a} > {b})"),
        AluOp::Sext8 => format!("({a} as u8 as i8) as i16 as u16"),
        AluOp::Join => format!("({a} & 0xFF) | (({b} & 0xFF) << 8)"),
    };
    match w {
        Width::W8 => format!("({body}) & 0xFF"),
        Width::W16 => body,
    }
}

/// Assign `expr` (a `u16` expression) to a destination.
fn assign(d: Dst, expr: &str) -> String {
    match d {
        Dst::Tmp(t) => format!("t{} = {expr};", t.0),
        Dst::Reg(r) if r == A => format!("r.a = ({expr}) as u8;"),
        Dst::Reg(r) if r == X => format!("r.x = ({expr}) as u8;"),
        Dst::Reg(r) if r == Y => format!("r.y = ({expr}) as u8;"),
        Dst::Reg(r) if r == S => format!("r.s = ({expr}) as u8;"),
        Dst::Reg(r) if r == PC => format!("r.pc = {expr};"),
        Dst::Reg(r) if r == P => format!("r.p = (({expr}) as u8 & !0x10) | 0x20;"),
        Dst::Reg(r) => format!("/* reg {} */", r.0),
    }
}

fn cycle_name(k: Cycle) -> &'static str {
    match k {
        Cycle::Fetch => "instruction-stream fetch",
        Cycle::Pointer => "zero-page pointer byte",
        Cycle::Data => "data",
        Cycle::Stack => "stack",
        Cycle::Vector => "interrupt vector byte",
        Cycle::Probe => "read at the uncorrected address (dummy if the page is crossed)",
        Cycle::Dummy => "DUMMY (value discarded, still a bus cycle)",
    }
}

fn ind(out: &mut String, depth: usize) {
    for _ in 0..depth {
        out.push_str("    ");
    }
}

/// Emit the body of one instruction's ops at `depth` indent levels.
fn emit_ops(out: &mut String, ops: &[Op], depth: usize) {
    let temps: std::collections::BTreeSet<u8> = ops
        .iter()
        .flat_map(|op| match *op {
            Op::Read {
                dst: Some(Dst::Tmp(t)),
                ..
            }
            | Op::Set {
                dst: Dst::Tmp(t), ..
            }
            | Op::Alu {
                dst: Dst::Tmp(t), ..
            }
            | Op::Machine(MachineOp::SelectVector { dst: t, .. }) => Some(t.0),
            _ => None,
        })
        .collect();
    for t in &temps {
        ind(out, depth);
        let _ = writeln!(out, "let mut t{t}: u16 = 0;");
    }
    let mut cycle = 2u32;
    let mut closers: Vec<usize> = Vec::new();
    for (i, op) in ops.iter().enumerate() {
        while closers.last() == Some(&i) {
            closers.pop();
            ind(out, depth + closers.len());
            out.push_str("}\n");
        }
        let d = depth + closers.len();
        let cond = if closers.is_empty() {
            ""
        } else {
            " (conditional)"
        };
        ind(out, d);
        match *op {
            Op::Read { dst, addr, kind } => {
                let _ = writeln!(out, "// cycle {cycle}{cond}: read, {}", cycle_name(kind));
                ind(out, d);
                let call = format!("bus.read(({}) as u16)", val(addr));
                match dst {
                    Some(dst) => {
                        let _ = writeln!(out, "{}", assign(dst, &format!("u16::from({call})")));
                    }
                    None => {
                        let _ = writeln!(out, "let _ = {call};");
                    }
                }
                cycle += 1;
            }
            Op::Write { addr, val: v, kind } => {
                let _ = writeln!(
                    out,
                    "// cycle {cycle}{cond}: write, {}",
                    if kind == Cycle::Dummy {
                        "write-back of the unmodified value".to_string()
                    } else {
                        cycle_name(kind).to_string()
                    }
                );
                ind(out, d);
                let _ = writeln!(
                    out,
                    "bus.write(({}) as u16, ({}) as u8);",
                    val(addr),
                    val(v)
                );
                cycle += 1;
            }
            Op::Set { dst, src } => {
                let _ = writeln!(out, "{}", assign(dst, &val(src)));
            }
            Op::Alu { dst, op, w, a, b } => {
                let _ = writeln!(out, "{}", assign(dst, &alu_expr(op, w, a, b)));
            }
            Op::SetFlag { flag, src } => {
                let m = flag.0;
                let _ = writeln!(
                    out,
                    "if ({}) != 0 {{ r.p |= {m:#04x}; }} else {{ r.p &= !{m:#04x}; }}",
                    val(src)
                );
            }
            Op::SkipUnless { cond, n } => {
                let _ = writeln!(out, "if ({}) != 0 {{", val(cond));
                closers.push(i + 1 + usize::from(n));
            }
            Op::Machine(m) => match m {
                MachineOp::BranchPollsEarly => {
                    let _ = writeln!(
                        out,
                        "// interrupt poll: taken branch, no page cross (not modelled)"
                    );
                }
                MachineOp::PollMaskFromFlags => {
                    let _ = writeln!(out, "// interrupt poll: I flag re-sampled (not modelled)");
                }
                MachineOp::InterruptEntry => {
                    let _ = writeln!(out, "// interrupt entry sequence (does not poll)");
                }
                MachineOp::SelectVector { dst, normal, .. } => {
                    let _ = writeln!(
                        out,
                        "t{} = {normal:#06x}; // NMI hijack of this vector is not modelled",
                        dst.0
                    );
                }
            },
        }
    }
    while let Some(_end) = closers.pop() {
        ind(out, depth + closers.len());
        out.push_str("}\n");
    }
}

/// Header comment: address, bytes and the trace disassembler's text.
fn insn_header(cpu: u32, bytes: &[u8]) -> String {
    struct Peek<'a>(u16, &'a [u8]);
    impl TracePeek for Peek<'_> {
        fn peek(&self, addr: u16) -> u8 {
            self.1
                .get(usize::from(addr.wrapping_sub(self.0)))
                .copied()
                .unwrap_or(0)
        }
    }
    let at = (cpu & 0xFFFF) as u16;
    let mut regs = crate::cpu::Cpu::default();
    regs.pc = at;
    let line = format_trace_line(&regs, &Peek(at, bytes), 0);
    // nestest columns: text starts at 16 and runs to the register dump.
    let text = line
        .get(16..)
        .and_then(|t| t.split("A:").next())
        .unwrap_or("")
        .trim();
    let hex: Vec<String> = bytes.iter().map(|b| format!("{b:02X}")).collect();
    format!("// ${at:04X}: {}  {text}", hex.join(" "))
}

/// Emit one lowered function as Rust source (no prelude).
#[must_use]
pub fn emit_lowered(f: &LoweredFunction) -> String {
    let mut out = String::new();
    let name = format!("f_{:04x}", f.entry_cpu & 0xFFFF);
    let _ = writeln!(
        out,
        "/// Atlas function entered at ${:04X}. Runs until `pc` leaves its\n\
         /// instructions or reaches one the interpreter must run.",
        f.entry_cpu & 0xFFFF
    );
    let _ = writeln!(out, "pub fn {name}<B: Bus>(r: &mut Regs, bus: &mut B) {{");
    out.push_str("    loop {\n        match r.pc {\n");
    let mut seen = HashSet::new();
    for blk in &f.blocks {
        for insn in &blk.insns {
            let at = insn.cpu & 0xFFFF;
            if !seen.insert(at) {
                continue; // the same instruction seen through two windows
            }
            let _ = writeln!(out, "            {at:#06x} => {{");
            let _ = writeln!(out, "                {}", insn_header(at, &insn.bytes));
            match &insn.ir.lowering {
                Lowering::Ir(ops) => {
                    out.push_str("                // cycle 1: opcode fetch\n");
                    out.push_str("                let _opcode = bus.read(r.pc);\n");
                    out.push_str("                r.pc = r.pc.wrapping_add(1);\n");
                    emit_ops(&mut out, ops, 4);
                }
                Lowering::Interpret(why) => {
                    let why = match why {
                        InterpretReason::Halt => "JAM".to_string(),
                        InterpretReason::Unstable(n) => format!("unstable {n}"),
                    };
                    let _ = writeln!(
                        out,
                        "                // interpret, do not lower: {why}\n                return;"
                    );
                }
            }
            out.push_str("            }\n");
        }
    }
    out.push_str("            _ => return,\n        }\n    }\n}\n");
    out
}

/// Emit a module: the prelude and one function per entry of `functions`.
#[must_use]
pub fn emit_module(atlas: &Atlas, functions: &[&Function], prg: &[u8]) -> String {
    let mut out = String::from(PRELUDE);
    for f in functions {
        out.push('\n');
        out.push_str(&emit_lowered(&lower_function(atlas, f, prg)));
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::rebuild::lower::lower_insn;
    use rf_rebuild::ir::{LoweredBlock, LoweredInsn};

    fn insn(cpu: u32, bytes: &[u8]) -> LoweredInsn {
        LoweredInsn {
            rom: 0,
            cpu,
            ir: lower_insn(bytes),
            bytes: bytes.to_vec(),
        }
    }

    #[test]
    fn emits_named_cycles_constants_and_interpreter_hand_offs() {
        let f = LoweredFunction {
            entry_cpu: 0x8000,
            blocks: vec![LoweredBlock {
                start_cpu: 0x8000,
                insns: vec![
                    insn(0x8000, &[0xAD, 0x02, 0x20]), // LDA $2002
                    insn(0x8003, &[0x9D, 0x00, 0x03]), // STA $0300,X (dummy read)
                    insn(0x8006, &[0x02]),             // JAM
                ],
            }],
        };
        let src = emit_lowered(&f);
        assert!(src.contains("pub fn f_8000<B: Bus>"));
        assert!(src.contains("// $8000: AD 02 20  LDA $2002"), "{src}");
        assert!(src.contains("cycle 4: read, data"));
        assert!(src.contains("bus.read((0x2002u16) as u16)"));
        assert!(src.contains("DUMMY"));
        assert!(src.contains("interpret, do not lower: JAM"));
        // Braces balance: every conditional group is closed.
        assert_eq!(src.matches('{').count(), src.matches('}').count());
    }
}
